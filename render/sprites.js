// Returns an SVG string (crisp pixels) scaled to `px` pixels per sprite pixel.
// opts: {flip:bool (mirror horizontally), tint:'#hex' (recolour for flashes: every pixel except the
// 'k' outline becomes the tint), tintAmount:0..1 (default 1; <1 blends toward the tint),
// tintOutline:bool (tint the outline too)}. Unknown names return ''. Results are cached per argument set.
window.spriteSVG = (function () {
  var cache = new Map();
  function rgb(h) {
    h = h.charAt(0) === '#' ? h.slice(1) : h;
    if (h.length === 3) h = h.charAt(0) + h.charAt(0) + h.charAt(1) + h.charAt(1) + h.charAt(2) + h.charAt(2);
    var n = parseInt(h, 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  function mix(a, b, t) {
    var A = rgb(a), B = rgb(b), o = '#';
    for (var i = 0; i < 3; i++) {
      var v = Math.round(A[i] + (B[i] - A[i]) * t);
      o += (v < 16 ? '0' : '') + v.toString(16);
    }
    return o;
  }
  return function spriteSVG(name, px, opts) {
    opts = opts || {};
    px = px || 1;
    var flip = !!opts.flip, tint = opts.tint || '';
    var amt = opts.tintAmount == null ? 1 : Math.max(0, Math.min(1, +opts.tintAmount));
    var tOut = !!opts.tintOutline;
    var key = name + '|' + px + '|' + (flip ? 1 : 0) + '|' + tint + '|' + amt + '|' + (tOut ? 1 : 0);
    var hit = cache.get(key);
    if (hit !== undefined) return hit;
    var s = window.SPRITES[name];
    if (!s) { cache.set(key, ''); return ''; }
    var base = window.SPRITE_PAL, own = s.pal || {}, rows = s.rows;
    var H = rows.length, W = rows[0].length, colOf = {};
    function col(ch) {
      var c = colOf[ch];
      if (c !== undefined) return c;
      c = own[ch] || base[ch];
      if (c && tint && (ch !== 'k' || tOut)) c = amt >= 1 ? tint : mix(c, tint, amt);
      return (colOf[ch] = c);
    }
    // Horizontal runs of one colour; identical runs on consecutive rows are merged into one taller rect.
    var rects = [], prev = new Map();
    for (var y = 0; y < H; y++) {
      var row = rows[y], cur = new Map(), x = 0;
      while (x < W) {
        var c = row.charAt(flip ? W - 1 - x : x);
        c = c === '.' ? null : col(c);
        var x0 = x;
        x++;
        while (x < W) {
          var d = row.charAt(flip ? W - 1 - x : x);
          if ((d === '.' ? null : col(d)) !== c) break;
          x++;
        }
        if (!c) continue;
        var k = x0 + ',' + (x - x0) + ',' + c, r = prev.get(k);
        if (r) r.h++;
        else rects.push(r = { x: x0, y: y, w: x - x0, h: 1, c: c });
        cur.set(k, r);
      }
      prev = cur;
    }
    var byCol = {}, order = [];
    for (var i = 0; i < rects.length; i++) {
      var q = rects[i];
      if (!byCol[q.c]) { byCol[q.c] = []; order.push(q.c); }
      byCol[q.c].push('<rect x="' + q.x + '" y="' + q.y + '" width="' + q.w + '" height="' + q.h + '"/>');
    }
    var svg = '<svg xmlns="http://www.w3.org/2000/svg" width="' + W * px + '" height="' + H * px +
      '" viewBox="0 0 ' + W + ' ' + H + '" shape-rendering="crispEdges">';
    for (var j = 0; j < order.length; j++) svg += '<g fill="' + order[j] + '">' + byCol[order[j]].join('') + '</g>';
    svg += '</svg>';
    cache.set(key, svg);
    return svg;
  };
})();
